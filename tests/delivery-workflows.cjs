const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('healthforcehub-pm.html', 'utf8');
const script = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m => m[1]).join('\n');
new vm.Script(script);
// Exercise the actual inline domain functions without cloud or browser state.
const start = script.indexOf('function defaultDelivery()');
const end = script.indexOf('installDeliveryUI();', start);
const store = new Map();
const context = vm.createContext({console, URL, navigator:{}, localStorage:{setItem:(k,v)=>store.set(k,v)}, document:{}, alert:()=>{}, isoNow:()=>new Date().toISOString(), uid:()=> 'evidence-id', clone:v=>JSON.parse(JSON.stringify(v)), persistJSON:(k,v)=>store.set(k,JSON.stringify(v)), isBlocked:t=>(t.blockedBy||[]).length>0});
vm.runInContext(`let tasks=[],projects=[],members=[],stakeholders=[],deliveryPending={},currentUser='Reviewer'; let editId=null; let sbMode='local'; let STAT_LBL={}; const WORK_TYPES=['epic','feature','story','task']; const WORK_LABELS={epic:'Epic',feature:'Feature',story:'User Story',task:'Task'};`,context);
vm.runInContext(script.slice(start,end),context);
vm.runInContext(`
globalThis.work=(id,type,parentId='',projectId='p')=>({id,title:id,projectId,status:'backlog',assignee:'Owner',blockedBy:[],delivery:{...defaultDelivery(),type,parentId}});
tasks=[work('e','epic'),work('f','feature','e'),work('s','story','f'),work('t','task','s')];
globalThis.valid=validateWorkItem(tasks[3]);
globalThis.badParent=validateWorkItem({...tasks[3],delivery:{...tasks[3].delivery,parentId:'e'}});
globalThis.crossProject=validateWorkItem({...tasks[3],projectId:'other'});
globalThis.changeParent=validateWorkItem({...tasks[0],delivery:{...tasks[0].delivery,type:'task'}});
globalThis.incomplete=validateWorkItem({...tasks[3],status:'done'});
tasks[3].delivery={...tasks[3].delivery,criteria:'Tests pass',evidence:[{type:'test',text:'Passed'}],reviewStatus:'approved',approval:{name:'Reviewer'}};
globalThis.complete=validateWorkItem({...tasks[3],status:'done'});
tasks[3].status='done';globalThis.progress=rollup(tasks[0]);
globalThis.badUrl=httpUrl('javascript:alert(1)');
globalThis.brief=buildAgentBrief(tasks[3]);
`,context);
assert.equal(context.valid,'');
assert.ok(context.badParent);
assert.ok(context.crossProject);
assert.ok(context.changeParent);
assert.ok(context.incomplete);
assert.equal(context.complete,'');
assert.equal(context.progress.done,1);
assert.equal(context.progress.total,1);
assert.equal(context.badUrl,false);
assert.match(context.brief,/Acceptance criteria/);
assert.match(context.brief,/Tests pass/);
assert.equal(context.safe('<img onerror="x">'),'&lt;img onerror=&quot;x&quot;&gt;');
console.log('Passed: hierarchy, cross-project validation, child protection, completion gate, rollups, safe links, and brief generation.');
